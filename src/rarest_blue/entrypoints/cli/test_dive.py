"""Write the hardcoded test dive the web app plays at /?test, straight from the McGill prompt bank.

    python -m rarest_blue.entrypoints.cli.test_dive            # rewrites web/app/lib/testDive.ts
    python -m rarest_blue.entrypoints.cli.test_dive --stdout   # print instead

Every prompt in the bank goes in, scored the way the real /api/daily scores a fresh day (list-order
priors, no players yet), so the tiers you see in test mode are the ones day-one players would get.
Rerun it after editing prompt_bank.py.
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

from ...application.gameplay import PromptPreview
from ...domain import rules, scoring
from ...domain.prompt_bank import PROMPTS
from ..http.routes import _preloaded_prompt

OUT = Path(__file__).resolve().parents[4] / "web" / "app" / "lib" / "testDive.ts"


def _prompt(p) -> dict:
    counts = scoring.prior_counts(p)
    out = _preloaded_prompt(PromptPreview(p, counts, 0))
    # The server shuffles the deep cuts it reveals; seed it so the generated file is stable.
    out["play"].update(scoring.reveal(counts, 0, random.Random(p.id)))  # noqa: S311 (fixture seed, not security)
    return out


def build_daily() -> dict:
    return {
        "day": "test",
        "number": 0,
        "time_limit": rules.TIME_LIMIT_SECONDS,
        "meters_per_point": rules.METERS_PER_POINT,
        "zones": [{"start": start, "name": name} for start, name in rules.ZONES],
        "prompts": [_prompt(p) for p in PROMPTS],
    }


def render(daily: dict) -> str:
    body = json.dumps(daily, indent=2, ensure_ascii=False)
    return (
        "// Generated by `python -m rarest_blue.entrypoints.cli.test_dive`. Do not edit by hand:\n"
        "// change src/rarest_blue/domain/prompt_bank.py and rerun it.\n"
        'import type { Daily } from "./api";\n\n'
        f"export const TEST_DAILY: Daily = {body};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--stdout", action="store_true", help="print instead of writing the web file")
    args = parser.parse_args()
    text = render(build_daily())
    if args.stdout:
        print(text, end="")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT} ({len(PROMPTS)} prompts)")


if __name__ == "__main__":
    main()
